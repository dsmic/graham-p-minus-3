# Generates GrahamPM/CycleEvenGen.lean and GrahamPM/CycleOddGen.lean (run from the `lean/` folder:
#   python3 scripts/gen_cycle.py).
# Each function (vertex at position p, jump at position p) is a chain of threshold conditions
# (additive form, no natural-number subtraction in the conditions); zigzag pieces additionally split
# by parity. For every piece k: an evaluation lemma (proved only by `rw` with `if_pos`/`if_neg`, each
# condition by `omega`), plus a case-split lemma (`omega`) and the main lemmas by case analysis +
# `omega`. The generator need not be trusted: Lean checks the generated proofs.
import sys
NSEG = {}
MAIN = {}

def build(name, par, conds, vals, nat):
    """conds: list of threshold conditions (strings in p, par); vals: list of values, each either an
    expression or (parity condition, value_if, value_else). The last value is the else branch."""
    assert len(vals) == len(conds) + 1
    ty = "ℕ" if nat else "ℤ"
    # definition
    lines = [f"def {name} ({par} p : ℕ) : {ty} :="]
    body = ""
    for c, v in zip(conds, vals[:-1]):
        body += f"  if {c} then {vexpr(v)}\n  else "
    body += vexpr(vals[-1])
    lines.append(body)
    # pieces
    segs = []      # (list of conditions as strings, value, list of (if_pos/if_neg, condition))
    for k, v in enumerate(vals):
        pre = [("if_neg", conds[j]) for j in range(k)]
        here = [("if_pos", conds[k])] if k < len(conds) else []
        hyps = [f"¬ ({conds[j]})" for j in ([k - 1] if k > 0 else [])] + ([conds[k]] if k < len(conds) else [])
        if isinstance(v, tuple):
            pc, va, vb = v
            segs.append((hyps + [pc], va, pre + here + [("if_pos", pc)]))
            segs.append((hyps + [f"¬ ({pc})"], vb, pre + here + [("if_neg", pc)]))
        else:
            segs.append((hyps, v, pre + here))
    return "\n".join(lines), segs

def vexpr(v):
    if isinstance(v, tuple):
        pc, va, vb = v
        return f"(if {pc} then {va} else {vb})"
    return v

def emit(fname, ns, defs):
    out = ["import Mathlib", "", f"/-! Generated by `scripts/gen_cycle.py`; do not edit by hand. -/", "",
           "set_option linter.unusedVariables false", "set_option linter.deprecated false", "",
           "namespace GrahamPM", ""]
    for (name, par, hyp, conds, vals, nat) in defs:
        d, segs = build(name, par, conds, vals, nat)
        out.append(d); out.append("")
        for k, (hyps, v, rws) in enumerate(segs):
            hs = " ∧ ".join(f"({x})" for x in hyps) if hyps else "True"
            rwl = ", ".join(f"{a} (show {('¬ (' + c + ')') if a == 'if_neg' else c} by omega)" for a, c in rws)
            out.append(f"lemma {name}_e{k} {{{par} : ℕ}} (p : ℕ) (hh : {hyp}) (hs : {hs}) :\n"
                       f"    {name} {par} p = {v} := by\n  unfold {name}\n  rw [{rwl}]\n")
        alts = " ∨\n    ".join("(" + (" ∧ ".join(f"({x})" for x in hyps) if hyps else "True") + ")" for hyps, _, _ in segs)
        out.append(f"lemma {name}_seg {{{par} : ℕ}} (p : ℕ) (hh : {hyp}) :\n    {alts} := by\n  omega\n")
        out.append(f"-- number of pieces of `{name}`: {len(segs)}\n")
        NSEG[name] = len(segs)
    out += MAIN.get(fname, [])
    out.append("end GrahamPM\n")
    open(fname, "w").write("\n".join(out))

