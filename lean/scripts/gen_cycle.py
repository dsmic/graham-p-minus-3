def ors(n): return " | ".join(["hs"] * n)
def firsts(name, n, arg, hyp, h):
    return "(first " + " ".join(f"| rw [{name}_e{k} {arg} {h} {hyp}]" for k in range(n)) + ")"
def firsts_at(name, n, arg, hyp, h, tgt):
    return "(first " + " ".join(f"| rw [{name}_e{k} {arg} {h} {hyp}] at {tgt}" for k in range(n)) + ")"
def main_lemmas(f, d, par, hyp, nlen, nf, nd):
    n = nlen
    L = []
    L.append(f"lemma {f}_lt {{{par} p : ℕ}} (hh : {hyp}) (hp : p < {n}) : {f} {par} p < {n} := by\n"
             f"  rcases {f}_seg p hh with {ors(nf)} <;> {firsts(f, nf, 'p', 'hs', 'hh')} <;> omega\n")
    L.append(f"lemma {f}_inj {{{par} p q : ℕ}} (hh : {hyp}) (hp : p < {n}) (hq : q < {n})\n"
             f"    (he : {f} {par} p = {f} {par} q) : p = q := by\n"
             f"  rcases {f}_seg p hh with {ors(nf)} <;> rcases {f}_seg q hh with {ors(nf).replace('hs', 'ht')} <;>\n"
             f"  {firsts_at(f, nf, 'p', 'hs', 'hh', 'he')} <;>\n  {firsts_at(f, nf, 'q', 'ht', 'hh', 'he')} <;> omega\n")
    L.append(f"lemma {d}_range {{{par} p : ℕ}} (hh : {hyp}) (hp : p < {n}) :\n"
             f"    (2 ≤ {d} {par} p ∧ {d} {par} p ≤ RMAX) ∨ (-(RMAX) ≤ {d} {par} p ∧ {d} {par} p ≤ -2) := by\n"
             f"  rcases {d}_seg p hh with {ors(nd)} <;> {firsts(d, nd, 'p', 'hs', 'hh')} <;> omega\n")
    L.append(f"lemma {d}_inj {{{par} p q : ℕ}} (hh : {hyp}) (hp : p < {n}) (hq : q < {n})\n"
             f"    (he : {d} {par} p = {d} {par} q) : p = q := by\n"
             f"  rcases {d}_seg p hh with {ors(nd)} <;> rcases {d}_seg q hh with {ors(nd).replace('hs', 'ht')} <;>\n"
             f"  {firsts_at(d, nd, 'p', 'hs', 'hh', 'he')} <;>\n  {firsts_at(d, nd, 'q', 'ht', 'hh', 'he')} <;> omega\n")
    L.append(f"lemma {f}_step {{{par} p : ℕ}} (hh : {hyp}) (hp : p + 1 < {n}) :\n"
             f"    ({f} {par} (p + 1) : ℤ) = {f} {par} p + {d} {par} p := by\n"
             f"  rcases {d}_seg p hh with {ors(nd)} <;> {firsts(d, nd, 'p', 'hs', 'hh')} <;>\n"
             f"  {firsts(f, nf, 'p', '(by omega)', 'hh')} <;>\n  {firsts(f, nf, '(p + 1)', '(by omega)', 'hh')} <;> omega\n")
    L.append(f"lemma {f}_last {{{par} : ℕ}} (hh : {hyp}) :\n"
             f"    ({f} {par} 0 : ℤ) = {f} {par} ({n} - 1) + {d} {par} ({n} - 1) := by\n"
             f"  {firsts(d, nd, '(' + n + ' - 1)', '(by omega)', 'hh')}\n"
             f"  {firsts(f, nf, '0', '(by omega)', 'hh')}\n"
             f"  {firsts(f, nf, '(' + n + ' - 1)', '(by omega)', 'hh')}\n  omega\n")
    return ["set_option maxHeartbeats 8000000 in\n" + x for x in L]
